/** Gear hash over UTF-16 code units. Only the terminal tail may be < min.
 * Never split a surrogate pair: independent UTF-8 encoding of its halves
 * would irreversibly replace them before hashing/compression. */
export function splitTraceString(text: string): string[] {
  const blocks: string[] = [];
  let start = 0;
  let hash = 0;
  for (let index = 0; index < text.length; index++) {
    const code = text.charCodeAt(index);
    hash = ((hash << 1) + GEAR[code & 255]!) >>> 0;
    const length = index + 1 - start;
    // Upper 12 bits cover more preceding characters than the low-bit mask,
    // which is biased by common prose suffixes (target: 2^12 characters).
    if (length < TRACE_BLOCK_MIN || ((hash >>> 20) !== 0 && length < TRACE_BLOCK_MAX)) continue;
    let end = index + 1;
    if (code >= 0xd800 && code <= 0xdbff && text.charCodeAt(end) >= 0xdc00 && text.charCodeAt(end) <= 0xdfff) {
      if (length < TRACE_BLOCK_MAX) continue;
      end--;
    }
    blocks.push(text.slice(start, end));
    start = end;
    index = end - 1;
    hash = 0;
  }
  if (start < text.length) blocks.push(text.slice(start));
  return blocks;
}
