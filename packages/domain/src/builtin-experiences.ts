  "var PADDLE_HALF = 0.09; // half-paddle width (fractions)",
  "var PADDLE_STEP = 0.06; // paddle movement per input nudge (fractions)",
  "var BALL_R = 0.014; // ball radius (fractions)",
  "var LIVES = 3; // balls per round",
  "var COLS = 8, ROWS = 4; // brick field",
  "var FIELD_LEFT = 0.06, FIELD_RIGHT = 0.94;",
