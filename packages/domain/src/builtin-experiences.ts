  "  // unverifiable, typed 422, nothing applied).",
  "  var r = context.random;",
  "  var speed = speedFor(lost);",
  "  var vx = (r.float() * 0.7 - 0.35) * speed;",
  "  return { x: px, y: PADDLE_Y - BALL_R - 0.01, vx: vx, vy: -Math.sqrt(speed * speed - vx * vx) };",
