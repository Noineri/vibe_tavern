  "var ROW_SCORES = [7, 5, 3, 1]; // top row pays most (classic Breakout)",
  "var SPEED_BASE = 0.5; // ball speed (fractions per second)",
  "var SPEED_PER_BALL = 0.07; // each lost ball makes the next one faster",
  "var MAX_BOUNCE = 0.8; // max |vx| as a share of speed off the paddle",
  "var FULL_FIELD = 0xFFFFFFFF; // 32 alive bricks, bit = row * COLS + col",
  "function speedFor(lost) { return SPEED_BASE + SPEED_PER_BALL * lost; }",
  "function clampBounce(off) {",
  "  if (off > MAX_BOUNCE) return MAX_BOUNCE;",
