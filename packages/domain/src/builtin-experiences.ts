  "      var row = Math.floor((ball.y - FIELD_TOP) / ROW_H);",
  "      var bit = 1 << (row * COLS + col);",
  "      if (bricks & bit) {",
  "        bricks = bricks & ~bit;",
  "        score += ROW_SCORES[row];",
